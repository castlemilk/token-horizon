#!/usr/bin/env node
/**
 * Builds the static benchmark report into report/dist/.
 *
 *   npx tsx report/build.mjs [--no-data] [--now 2026-11-10T12:00:00.000Z]
 *
 * Steps:
 *   1. runs report/build-data.mjs (writes dist/data/board.js and board.json)
 *      unless --no-data is passed; --now is passed through to it;
 *   2. copies template/index.html, report.css and report.js into dist/;
 *   3. copies the two product fonts into dist/fonts/;
 *   4. generates dist/tokens.css from the light and dark --th-* blocks of
 *      the product's docs/theme.css, so the report stays in step with it.
 *
 * dist/gallery is written by the capture step and is left in place. Bundles from
 * the earlier frame design (dist/artifacts, dist/frame.js) are removed here: the
 * page never runs model-written HTML, so nothing of that kind is shipped.
 * Prints the path of dist/index.html to open.
 */
import { spawnSync } from 'node:child_process'
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const benchRoot = resolve(here, '..')
const tokenRoot = resolve(benchRoot, '..')
const templateDir = join(here, 'template')
const dist = join(here, 'dist')
const themeCss = join(tokenRoot, 'docs', 'theme.css')
const fontsDir = join(tokenRoot, 'docs', 'fonts')
const FONTS = ['HubotSansVF-Regular.ttf', 'JetBrainsMono-Regular.ttf']

const argv = process.argv.slice(2)
const noData = argv.includes('--no-data')
const passthrough = []
for (let i = 0; i < argv.length; i++) {
  if (argv[i] === '--now') {
    passthrough.push('--now', argv[i + 1])
    i++
  } else if (argv[i].startsWith('--now=')) {
    passthrough.push(argv[i])
  }
}

if (!noData) {
  const run = spawnSync('npx', ['tsx', 'report/build-data.mjs', ...passthrough], {
    cwd: benchRoot,
    stdio: 'inherit'
  })
  if (run.status !== 0) {
    console.error('build: data build failed; the page was not rebuilt')
    process.exit(run.status ?? 1)
  }
}

mkdirSync(dist, { recursive: true })
for (const stale of ['artifacts', 'frame.js']) rmSync(join(dist, stale), { recursive: true, force: true })
for (const file of ['index.html', 'report.css', 'report.js']) {
  copyFileSync(join(templateDir, file), join(dist, file))
}

mkdirSync(join(dist, 'fonts'), { recursive: true })
for (const font of FONTS) {
  const src = join(fontsDir, font)
  if (!existsSync(src)) throw new Error(`build: missing font ${src}`)
  copyFileSync(src, join(dist, 'fonts', font))
}

/** The --th-* declarations (and colour-scheme) inside the first block that matches. */
function declarations(css, pattern, label) {
  const match = css.match(pattern)
  if (!match) throw new Error(`build: could not find the ${label} block in docs/theme.css`)
  return match[1]
    .split('\n')
    .map((line) => line.trim())
    .filter((line) => /^--th-[\w-]+\s*:/.test(line))
}

const css = readFileSync(themeCss, 'utf8')
const light = declarations(css, /:root,\s*html\[data-theme="light"\]\s*\{([\s\S]*?)\n\}/, 'light')
const dark = declarations(css, /\nhtml\[data-theme="dark"\]\s*\{([\s\S]*?)\n\}/, 'dark')
if (light.length < 10 || dark.length < 10) throw new Error('build: theme.css blocks look incomplete')
const tokens = [
  '/* Generated by report/build.mjs from docs/theme.css. Do not edit. */',
  ':root, html[data-theme="light"] {',
  '  color-scheme: light;',
  ...light.map((d) => `  ${d}`),
  '}',
  'html[data-theme="dark"] {',
  '  color-scheme: dark;',
  ...dark.map((d) => `  ${d}`),
  '}',
  '@media (prefers-color-scheme: dark) {',
  '  :root:not([data-theme="light"]) {',
  '    color-scheme: dark;',
  ...dark.map((d) => `    ${d}`),
  '  }',
  '}',
  ''
].join('\n')
writeFileSync(join(dist, 'tokens.css'), tokens)

const indexPath = join(dist, 'index.html')
console.log(`report built: ${light.length} light and ${dark.length} dark tokens from docs/theme.css`)
console.log(indexPath)
console.log(`open: file://${indexPath}`)
